-- ============================================================================
-- 문화·체육 시설 표 신설 (v1.10.0, 2026-10-14)
--
-- 경기데이터드림이 제공하는 장애인 문화·체육 데이터 4종을 한 표에 담는다.
--   braille_lib    점자도서관 현황            (Ggbrlllibrry)
--   booknarae_lib  책나래서비스 제공도서관 현황 (Gglibrryprovsnservc)
--   sports_fac     장애인체육시설 현황         (Ggdspsnphstrnfaclt)
--   sports_org     시군별 장애인체육회 현황     (Ggsigundspsnphstrn)
--
-- 한 표로 묶은 이유
--   · 4종의 칸이 거의 같다(기관명·주소·좌표·전화·홈페이지). 종류별로 다른 칸은
--     설치신고일(점자도서관·체육시설)과 법인명(점자도서관) 2개뿐이다.
--   · 소비처(주변 시설 안내, 공개 API)는 "종류 + 위치 반경" 으로 읽는다.
--   · 체육회는 시설이 아니라 단체지만, 사무국 위치·연락처를 안내한다는 점에서
--     같은 방식으로 쓰인다. 표 설명에 "시설 및 유관 단체 거점" 으로 적는다.
--
-- 키 설계
--   · 원천에 고유키가 없다. 적재기(08-IITP-DABT-PreProcessing GG_CULTURE)가
--     (이름 + 정규화 주소) 로 기존 행을 찾아 갱신하고, 원천에서 사라진 행은
--     논리삭제(del_yn='Y'), 다시 나타나면 같은 행을 되살린다(facility_id 유지).
--   · 유일성은 활성 행에만 건다(부분 유니크). 논리삭제 행은 이력으로 남아도
--     제약에 걸리지 않는다. 도로명이 없는 행은 지번 주소로 대신한다.
--
-- 외부 연동 정보
--   · sys_ext_api_info 에 GG_CULTURE 1행을 등록한다. 인증키는 저장소에 두지
--     않는다 — 같은 경기데이터드림 키를 쓰는 GG_TOILET 행이 있으면 그 값을
--     복사하고, 없으면 NULL 로 두어 운영자가 채운다(적재기는 환경변수
--     GG_CULTURE_API_KEY 로도 키를 받는다).
--
-- 모두 IF NOT EXISTS / NOT EXISTS 라 재실행해도 결과가 같다.
-- ============================================================================

BEGIN;

-- 1) 문화·체육 시설 ---------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.poi_culture_sports_facility (
	facility_id int4 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START 1 CACHE 1 NO CYCLE) NOT NULL ,
	facility_type varchar(20) NOT NULL ,            -- braille_lib / booknarae_lib / sports_fac / sports_org
	sido_code varchar(10) NULL ,                    -- 내부 시도 코드(sys_common_code sido_code, 경기 9410000)
	sigun_cd varchar(10) NULL ,                     -- 원천 시군 코드
	sigun_nm varchar(40) NULL ,                     -- 원천 시군명(원천 값 그대로 — 주소의 시군과 다를 수 있다)
	name varchar(200) NOT NULL ,                    -- 기관·시설·단체명
	addr_road varchar(600) NULL ,                   -- 도로명 주소
	addr_jibun varchar(600) NULL ,                  -- 지번 주소
	zip_code varchar(10) NULL ,                     -- 우편번호
	latitude double precision NULL ,                -- 위도(WGS84). 국내 범위를 벗어난 값은 적재기가 NULL 로 둔다
	longitude double precision NULL ,               -- 경도(WGS84)
	tel varchar(40) NULL ,                          -- 대표 전화
	homepage varchar(400) NULL ,                    -- 홈페이지
	install_report_dt date NULL ,                   -- 설치신고일(점자도서관·장애인체육시설만)
	corp_name varchar(200) NULL ,                   -- 운영 법인명(점자도서관만)
	source varchar(40) NULL ,                       -- 출처 코드(ext_sys_code)
	del_yn bpchar(1) DEFAULT 'N' NULL ,
	created_at timestamptz DEFAULT CURRENT_TIMESTAMP NOT NULL ,
	updated_at timestamptz DEFAULT CURRENT_TIMESTAMP NULL ,
	deleted_at timestamptz NULL ,
	created_by varchar(40) NOT NULL ,
	updated_by varchar(40) NULL ,
	deleted_by varchar(40) NULL ,
	CONSTRAINT pkey_poi_culture_sports_facility PRIMARY KEY (facility_id) ,
	-- 종류 값 오타로 다른 종류가 생기는 것을 막는다. 종류를 늘릴 때는 이 제약을 함께 고친다.
	CONSTRAINT chk_poi_culture_sports_facility_type
		CHECK (facility_type IN ('braille_lib', 'booknarae_lib', 'sports_fac', 'sports_org'))
);

COMMENT ON TABLE public.poi_culture_sports_facility
    IS '장애인 문화·체육 시설 및 유관 단체 거점 — 점자도서관·책나래 제공도서관·장애인체육시설·장애인체육회';
COMMENT ON COLUMN public.poi_culture_sports_facility.facility_type
    IS 'braille_lib(점자도서관) / booknarae_lib(책나래서비스 제공도서관) / sports_fac(장애인체육시설) / sports_org(장애인체육회)';
COMMENT ON COLUMN public.poi_culture_sports_facility.sigun_nm
    IS '원천 시군명 그대로. 원천 오기로 주소의 시군과 다른 행이 있다(위치 판단은 주소·좌표 기준)';

-- 활성 행 유일성: (종류, 이름, 도로명→없으면 지번). 논리삭제 행은 제외.
CREATE UNIQUE INDEX IF NOT EXISTS uidx_poi_culture_sports_facility_key
    ON public.poi_culture_sports_facility USING btree (facility_type, name, coalesce(addr_road, addr_jibun, ''))
    WHERE del_yn = 'N';
-- 소비처 조회 형태(종류 + 위치) 하나로 둔다. 행 수가 수백 건이라 인덱스를 늘리지 않는다.
CREATE INDEX IF NOT EXISTS idx_poi_culture_sports_facility_type_loc
    ON public.poi_culture_sports_facility USING btree (facility_type, latitude, longitude)
    WHERE del_yn = 'N';

-- 2) 외부 연동 시스템 코드 ---------------------------------------------------
INSERT INTO public.sys_common_code
    (grp_id, grp_nm, code_id, code_nm, parent_grp_id, parent_code_id, code_type, code_lvl,
     sort_order, use_yn, del_yn, code_des, memo, created_at, created_by)
SELECT 'ext_sys_code', '외부 연동 시스템 코드', 'GG_CULTURE', '경기데이터드림 장애인 문화·체육 시설',
       null, null, 'S', 1,
       (SELECT coalesce(max(sort_order), 0) + 1 FROM public.sys_common_code WHERE grp_id = 'ext_sys_code'),
       'Y', 'N',
       '점자도서관·책나래 제공도서관·장애인체육시설·시군별 장애인체육회 (poi_culture_sports_facility)', '',
       CURRENT_TIMESTAMP, 'SYS-MANUAL'
WHERE NOT EXISTS (
    SELECT 1 FROM public.sys_common_code WHERE grp_id = 'ext_sys_code' AND code_id = 'GG_CULTURE'
);

-- 3) 외부 API 정보 ------------------------------------------------------------
-- ext_url 은 서비스 공통 주소다. 적재기가 뒤에 서비스명 4개를 붙여 호출한다.
INSERT INTO public.sys_ext_api_info
    (if_name, ext_sys, ext_url, auth, data_format, latest_sync_time, memo, del_yn,
     created_at, updated_at, created_by)
SELECT '경기데이터드림 장애인 문화·체육 시설', 'GG_CULTURE', 'https://openapi.gg.go.kr',
       (SELECT auth FROM public.sys_ext_api_info
         WHERE ext_sys = 'GG_TOILET' AND del_yn = 'N' ORDER BY ext_api_id LIMIT 1),
       'JSON', null,
       'poi_culture_sports_facility 4종(경기도 전체). 원천 연간 갱신, 매월 수집', 'N',
       CURRENT_TIMESTAMP, CURRENT_TIMESTAMP, 'SYS-MANUAL'
WHERE NOT EXISTS (
    SELECT 1 FROM public.sys_ext_api_info WHERE ext_sys = 'GG_CULTURE'
);

COMMIT;
