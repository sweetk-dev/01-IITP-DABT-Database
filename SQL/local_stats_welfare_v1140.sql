-- 2) 경기 읍면동 등록장애인 --------------------------------------------------
CREATE TABLE IF NOT EXISTS public.stats_gg_dis_reg_emd (
	id int4 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START 1 CACHE 1 NO CYCLE) NOT NULL,
	base_dt date NOT NULL,              -- 원천 기준일(DATA_COLCT_DE). 시군마다 다르다
	sigun_nm varchar(40) NOT NULL,      -- 시군명
	gu_nm varchar(40) NULL,             -- 일반구명(구가 없는 시군은 NULL)
	emd_nm varchar(60) NOT NULL,        -- 읍면동명(원천 값 그대로 — 행정동 개칭 전 이름일 수 있다)
	dis_type varchar(20) NOT NULL,      -- 장애유형(15종). '소계'·'전체'·'합계' 행은 적재하지 않는다
	tot_cnt int4 NULL,                  -- 등록장애인 수
	male_cnt int4 NULL,
	female_cnt int4 NULL,
	sev_cnt int4 NULL,                  -- 심한 장애
	sev_male_cnt int4 NULL,
	sev_female_cnt int4 NULL,
	nsev_cnt int4 NULL,                 -- 심하지 않은 장애
	nsev_male_cnt int4 NULL,
	nsev_female_cnt int4 NULL,
	created_at timestamptz DEFAULT CURRENT_TIMESTAMP NOT NULL,
	updated_at timestamptz DEFAULT CURRENT_TIMESTAMP,
	created_by varchar(40) NOT NULL,
	updated_by varchar(40) NULL,
	CONSTRAINT pkey_stats_gg_dis_reg_emd PRIMARY KEY (id)
);
CREATE UNIQUE INDEX IF NOT EXISTS uidx_stats_gg_dis_reg_emd_key
    ON public.stats_gg_dis_reg_emd USING btree (sigun_nm, COALESCE(gu_nm, ''), emd_nm, dis_type, base_dt);
CREATE INDEX IF NOT EXISTS idx_stats_gg_dis_reg_emd_sigun_dt
    ON public.stats_gg_dis_reg_emd USING btree (sigun_nm, base_dt);
COMMENT ON TABLE public.stats_gg_dis_reg_emd
    IS '경기도 내 등록장애인 집계현황(읍면동별·유형별·정도별, 경기데이터드림 GGREDISPERST). 시군별 기준일 판을 쌓는다';
COMMENT ON COLUMN public.stats_gg_dis_reg_emd.base_dt
    IS '원천 기준일 — 시군마다 다르다. 시군 비교·경기 합계에는 기준일을 함께 표시할 것';

CREATE OR REPLACE VIEW public.v_stats_gg_dis_reg_emd_latest AS
SELECT e.*
  FROM public.stats_gg_dis_reg_emd e
  JOIN (SELECT sigun_nm, max(base_dt) AS base_dt FROM public.stats_gg_dis_reg_emd GROUP BY sigun_nm) m
    ON m.sigun_nm = e.sigun_nm AND m.base_dt = e.base_dt;
COMMENT ON VIEW public.v_stats_gg_dis_reg_emd_latest IS '시군별 최신 기준일 판만 — 합산·비교는 이 뷰로';

-- 3) 장애인복지시설 ----------------------------------------------------------
