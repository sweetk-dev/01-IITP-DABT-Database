    ON public.poi_welfare_facility USING btree (facility_type, name, coalesce(addr_road, addr_jibun, ''))
    WHERE del_yn = 'N';
CREATE INDEX IF NOT EXISTS idx_poi_welfare_facility_type_sigun
    ON public.poi_welfare_facility USING btree (facility_type, sigun_nm)
    WHERE del_yn = 'N';
CREATE INDEX IF NOT EXISTS idx_poi_welfare_facility_type_loc
    ON public.poi_welfare_facility USING btree (facility_type, latitude, longitude)
    WHERE del_yn = 'N';

